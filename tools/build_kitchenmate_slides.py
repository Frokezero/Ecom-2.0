def rgb(h): return RGBColor.from_string(h.lstrip('#'))
def rect(s,x,y,w,h,fill, radius=False, line=None):
    a=s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    a.fill.solid(); a.fill.fore_color.rgb=rgb(fill)
    a.line.fill.background() if not line else None
    if line: a.line.color.rgb=rgb(line)
    if radius:
        try: a.adjustments[0]=0.15
        except: pass
    return a
def txt(s,text,x,y,w,h,size=24,color=GREEN,bold=False,align=None):
    box=s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf=box.text_frame; tf.clear(); tf.word_wrap=True
    tf.margin_left=tf.margin_right=Inches(.04);tf.margin_top=tf.margin_bottom=Inches(.02)
    for i,line in enumerate(text.split('\n')):
        p=tf.paragraphs[0] if i==0 else tf.add_paragraph();p.text=line
        p.font.name=FONT;p.font.size=Pt(size);p.font.bold=bold;p.font.color.rgb=rgb(color)
        p.space_after=Pt(4)
        if align:p.alignment=align
    return box
